"""Generate the small, offline Chinese bitmap font used by Indicator.

Requires Pillow. The generated header is shipped with the firmware, so normal
PlatformIO builds do not require Pillow or the source OTF.
"""
from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FONT = ROOT / ".tools/fonts/NotoSansSC-Regular.otf"
DEFAULT_OUTPUT = ROOT / "firmware/indicator/include/ui_glyphs.h"


def required_characters() -> list[str]:
    chars = set(chr(c) for c in range(32, 127))
    for folder in (ROOT / "firmware/indicator/src", ROOT / "firmware/indicator/include"):
        for source in sorted(folder.glob("*")):
            if source.suffix not in (".cpp", ".h") or source.name == "ui_glyphs.h":
                continue
            # Include source comments too: small conservative over-inclusion is
            # preferable to silently missing a visible label or local caption.
            chars.update(c for c in source.read_text(encoding="utf-8")
                         if ord(c) > 127 and c.isprintable() and ord(c) <= 0xFFFF)
    return sorted(chars, key=ord)


def rasterize(font: ImageFont.FreeTypeFont, char: str) -> tuple[int, list[int]]:
    canvas = Image.new("L", (16, 16))
    # Common baseline preserves punctuation and descenders across Latin/CJK.
    ImageDraw.Draw(canvas).text((0, 14), char, font=font, fill=255, anchor="ls")
    advance = 16 if ord(char) >= 0x2E80 else min(16, max(1, math.ceil(font.getlength(char))))
    rows = [sum(1 << (15 - x) for x in range(16) if canvas.getpixel((x, y)) >= 100)
            for y in range(16)]
    if char != " " and not any(rows):
        raise ValueError(f"Empty glyph: U+{ord(char):04X}")
    return advance, rows


def generate(font_path: Path, output: Path, preview: Path | None = None) -> int:
    font = ImageFont.truetype(str(font_path), 16)
    chars = required_characters()
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    lines = ["// Generated by tools/build_indicator_font.py. Do not edit.",
             "// Noto Sans SC, SIL OFL 1.1; see assets/fonts/OFL.txt.",
             f"// Source font SHA256: {digest}", "#pragma once", "#include <stddef.h>",
             "#include <stdint.h>", "namespace ui_font {",
             "struct Glyph { uint32_t code; uint8_t advance; uint16_t rows[16]; };",
             "static const Glyph kGlyphs[] = {"]
    sheet = Image.new("RGB", (24 * 24, math.ceil(len(chars) / 24) * 24), "#f4f1de")
    for index, char in enumerate(chars):
        advance, rows = rasterize(font, char)
        lines.append("  {0x%04X, %d, {%s}}," %
                     (ord(char), advance, ",".join(f"0x{row:04X}" for row in rows)))
        for y, row in enumerate(rows):
            for x in range(16):
                if row & (1 << (15 - x)):
                    sheet.putpixel(((index % 24) * 24 + x + 4,
                                    (index // 24) * 24 + y + 4), (31, 50, 40))
    lines += ["};", "constexpr size_t kCount = sizeof(kGlyphs) / sizeof(kGlyphs[0]);",
              f"constexpr size_t kFallback = {chars.index('?')};", "}", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    if preview:
        preview.parent.mkdir(parents=True, exist_ok=True)
        sheet.save(preview)
    return len(chars)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--preview", type=Path)
    parser.add_argument("--check", action="store_true", help="Check source character coverage without changing files")
    args = parser.parse_args()
    if args.check:
        present = {int(code, 16) for code in re.findall(r"\{0x([0-9A-F]+),", args.output.read_text(encoding="utf-8"))}
        missing = [char for char in required_characters() if ord(char) not in present]
        if missing:
            parser.error("Font needs regeneration; missing: " + "".join(missing))
        print(f"PASS: all {len(required_characters())} source characters have glyphs")
    else:
        print(f"Generated {generate(args.font, args.output, args.preview)} glyphs: {args.output}")


if __name__ == "__main__":
    main()
